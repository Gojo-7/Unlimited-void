import * as THREE from "three";

import { SCENE } from "./Constants.js";

export class Scene {

    constructor() {

        //////////////////////////////////////////////////////
        // SCENE
        //////////////////////////////////////////////////////

        this.instance = new THREE.Scene();

        //////////////////////////////////////////////////////
        // BACKGROUND
        //////////////////////////////////////////////////////

        this.instance.background =
        new THREE.Color(

            SCENE.background

        );

        //////////////////////////////////////////////////////
        // FOG
        //////////////////////////////////////////////////////

        this.instance.fog =
        new THREE.FogExp2(

            SCENE.fogColor,

            SCENE.fogDensity

        );

    }

    //////////////////////////////////////////////////////////
    // GET
    //////////////////////////////////////////////////////////

    get() {

        return this.instance;

    }

}