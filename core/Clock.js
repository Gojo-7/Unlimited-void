import * as THREE from "three";

export class Clock {

    constructor() {

        //////////////////////////////////////////////////////
        // THREE CLOCK
        //////////////////////////////////////////////////////

        this.clock = new THREE.Clock();

        //////////////////////////////////////////////////////
        // TIME
        //////////////////////////////////////////////////////

        this.elapsedTime = 0;

        this.deltaTime = 0;

    }

    //////////////////////////////////////////////////////////
    // UPDATE
    //////////////////////////////////////////////////////////

    update() {

        this.deltaTime =
        this.clock.getDelta();

        this.elapsedTime =
        this.clock.getElapsedTime();

    }

    //////////////////////////////////////////////////////////
    // GETTERS
    //////////////////////////////////////////////////////////

    getDelta() {

        return this.deltaTime;

    }

    getElapsed() {

        return this.elapsedTime;

    }

    //////////////////////////////////////////////////////////
    // RESET
    //////////////////////////////////////////////////////////

    reset() {

        this.clock.start();

        this.elapsedTime = 0;

        this.deltaTime = 0;

    }

}