import * as THREE from "three";

import { CAMERA } from "./Constants.js";

export class Camera {

    constructor() {

        //////////////////////////////////////////////////////
        // CAMERA
        //////////////////////////////////////////////////////

        this.instance =
        new THREE.PerspectiveCamera(

            CAMERA.fov,

            window.innerWidth /
            window.innerHeight,

            CAMERA.near,

            CAMERA.far

        );

        //////////////////////////////////////////////////////
        // INITIAL POSITION
        //////////////////////////////////////////////////////

        this.instance.position.copy(

            CAMERA.position

        );

    }

    //////////////////////////////////////////////////////////
    // GET CAMERA
    //////////////////////////////////////////////////////////

    get() {

        return this.instance;

    }

    //////////////////////////////////////////////////////////
    // LOOK AT
    //////////////////////////////////////////////////////////

    lookAt(target) {

        this.instance.lookAt(target);

    }

    //////////////////////////////////////////////////////////
    // SET POSITION
    //////////////////////////////////////////////////////////

    setPosition(x, y, z) {

        this.instance.position.set(

            x,
            y,
            z

        );

    }

    //////////////////////////////////////////////////////////
    // GET POSITION
    //////////////////////////////////////////////////////////

    getPosition() {

        return this.instance.position;

    }

    //////////////////////////////////////////////////////////
    // RESIZE
    //////////////////////////////////////////////////////////

    resize(width, height) {

        this.instance.aspect =

            width / height;

        this.instance.updateProjectionMatrix();

    }

}